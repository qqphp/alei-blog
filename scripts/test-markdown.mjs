import assert from 'node:assert/strict';
import { register } from 'node:module';
import { Window } from 'happy-dom';
register('./ui-test-loader.mjs', import.meta.url);
const window = new Window({ url: 'http://localhost:3000' });
for (const name of ['window', 'document', 'navigator', 'HTMLElement', 'HTMLScriptElement', 'Element', 'Node', 'Event', 'MutationObserver'])
  Object.defineProperty(globalThis, name, { value: name === 'window' ? window : window[name], configurable: true });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const { createElement: h, act } = await import('react');
const { render, screen, cleanup, fireEvent } = await import('@testing-library/react');
const { MarkdownContent } = await import('../components/markdown-content.tsx');
const { default: Editor } = await import('../components/admin-markdown-editor-content.tsx');
const { default: Vditor } = await import('./vditor-test-double.mjs');
const realFetch = globalThis.fetch;
const structure = node => node.nodeType === 1
  ? [node.tagName, [...node.attributes].map(({ name, value }) => [name, value]).sort((a, b) => a[0].localeCompare(b[0])), [...node.childNodes].map(structure)]
  : node.textContent;
try {
  const source = '## 中文标题\n\n- 条目\n  - 子项\n\n1. 有序项\n\n- [x] 完成\n\n> 引用\n\n| 标题 | 值 |\n| --- | --- |\n| 内容 | 1 |\n\n![图片](/image.png)\n\n[安全链接](https://example.com)\n\n```js\nconst answer = 42;\n```\n\n```unknown-language\nplain code\n```\n\n```\nno language\n```\n\n<script>alert(1)</script>\n\n[危险](javascript:alert%281%29)';
  const view = render(h(MarkdownContent, { source }));
  assert.equal(view.container.querySelector('h2').id, 'heading-1');
  assert.equal(view.container.querySelector('ul ul li').textContent, '子项');
  assert.ok(view.container.querySelector('input[type=checkbox]').checked);
  assert.equal(view.container.querySelector('td').textContent, '内容');
  assert.equal(view.container.querySelector('img').getAttribute('src'), '/image.png');
  assert.ok(view.container.querySelector('code.hljs .hljs-keyword'));
  assert.equal(view.container.querySelectorAll('pre code:not(.hljs)').length, 2);
  assert.equal(view.container.querySelector('script'), null);
  assert.equal(view.container.querySelector('a[href^="javascript:"]'), null);
  const expectedMarkup = view.container.querySelector('.site-markdown').cloneNode(true);
  expectedMarkup.normalize();
  cleanup();
  const changes = [], working = [];
  const props = { label: '正文', value: source, onChange: value => changes.push(value), onWorking: value => working.push(value) };
  const editorView = render(h(Editor, props));
  await screen.findByRole('textbox', { name: '正文 Markdown' });
  const instance = Vditor.instances.at(-1);
  assert.equal(instance.options.mode, 'ir');
  assert.equal(instance.options.cache.enable, false);
  assert.equal(instance.options.cdn, '/vendor/vditor');
  assert.deepEqual([...editorView.container.querySelector('.site-markdown').childNodes].map(structure), [...expectedMarkup.childNodes].map(structure));
  assert.equal(instance.options.outline.enable, true);
  assert.equal(instance.options.counter.type, 'text');
  assert.ok(['outline', 'indent', 'outdent'].every(item => instance.options.toolbar.includes(item)));
  assert.match(instance.vditor.lute.Md2VditorIRDOM('$1+x$'), /language-math/);
  const before = instance.input;
  await act(async () => fireEvent.input(before, { target: { value: '中文更新' } }));
  editorView.rerender(h(Editor, { ...props, value: changes.at(-1) }));
  assert.equal(instance.input, before);
  assert.equal(instance.getValue(), '中文更新');
  assert.equal(instance.counter.textContent, '4 字');
  editorView.rerender(h(Editor, { ...props, value: '' }));
  assert.equal(instance.counter.textContent, '0 字');
  globalThis.fetch = async () => Response.json({ url: '/api/media/image.webp', name: 'image.webp' });
  await act(async () => instance.options.upload.handler([new window.File(['image'], '中文图片.png', { type: 'image/png' })]));
  assert.match(changes.at(-1), /!\[中文图片.png\]\(\/api\/media\/image.webp\)/);
  assert.deepEqual(working.slice(-2), [true, false]);
  const uploaded = changes.at(-1);
  globalThis.fetch = async () => Response.json({ error: '上传失败' }, { status: 500 });
  await act(async () => instance.options.upload.handler([new window.File(['image'], 'fail.png', { type: 'image/png' })]));
  assert.equal(instance.getValue(), uploaded);
  assert.ok(screen.getByText('上传失败'));
  let requests = 0;
  globalThis.fetch = async () => { requests++; return Response.json({}); };
  await act(async () => instance.options.upload.handler([new window.File([new Uint8Array(20 * 1024 * 1024 + 1)], 'large.png', { type: 'image/png' })]));
  assert.equal(requests, 0);
  assert.ok(screen.getByText('文件不能超过 20 MB'));
  let finish;
  globalThis.fetch = () => new Promise(resolve => { finish = resolve; });
  let pending;
  await act(async () => { pending = instance.options.upload.handler([new window.File(['image'], 'late.png', { type: 'image/png' })]); });
  editorView.rerender(h(Editor, { ...props, value: '另一条正文' }));
  await act(async () => { finish(Response.json({ url: '/api/media/late.webp' })); await pending; });
  assert.equal(instance.getValue(), '另一条正文');
  assert.equal(instance.clearedStack, true);
  await act(async () => { pending = instance.options.upload.handler([new window.File(['image'], 'unmounted.png', { type: 'image/png' })]); });
  editorView.unmount();
  await act(async () => { finish(Response.json({ url: '/api/media/unmounted.webp' })); await pending; });
  assert.equal(instance.getValue(), '另一条正文');
  assert.ok(instance.destroyed);
  const dollarText = '价格 \\$42，公式 $1+x$\n\n$$\nx^2\n$$';
  const dollarEditor = render(h(Editor, { ...props, value: dollarText }));
  await screen.findByRole('textbox', { name: '正文 Markdown' });
  const dollarInstance = Vditor.instances.at(-1);
  assert.doesNotMatch(dollarInstance.initialMarkup, /language-math/,
    'initial content must not render math before editor configuration');
  const dollarMarkup = document.createElement('div');
  dollarMarkup.innerHTML = dollarInstance.vditor.lute.Md2VditorIRDOM(dollarText);
  assert.ok(dollarMarkup.querySelector('.vditor-ir__preview .language-math'));
  assert.ok(dollarEditor.container.querySelector('.katex-display'));
  assert.equal(dollarInstance.getValue(), dollarText);
  dollarEditor.unmount();
  const mathSource = '## 公式 $x^2$\n\n价格 \\$42 和 \\$50，数字 $1+2$，分数 $\\frac{a}{b}$。\n\n$$\n\\sum_{i=1}^{n} i + \\begin{pmatrix}1&2\\\\3&4\\end{pmatrix}\n$$\n\n`$code$`\n\n```js\nconst price = "$42";\n```\n\n错误 $\\badcommand{<img src=x onerror=alert(1)>}$\n\n$\\href{javascript:alert(1)}{危险}$';
  const mathView = render(h(MarkdownContent, { source: mathSource }));
  assert.equal(mathView.container.querySelector('h2').id, 'heading-1');
  assert.ok(mathView.container.querySelectorAll('.katex').length >= 4);
  assert.ok(mathView.container.querySelector('.katex-display'));
  const invalidView = render(h(MarkdownContent, { source: '$\\frac{1}{<img src=x onerror=alert(1)>$' }));
  assert.ok(invalidView.container.querySelector('.katex-error'));
  assert.equal(invalidView.container.querySelector('img'), null);
  invalidView.unmount();
  assert.ok(mathView.container.querySelector('math'));
  assert.equal(mathView.container.querySelector('img'), null);
  assert.equal(mathView.container.querySelector('a[href^="javascript:"]'), null);
  assert.match(mathView.container.textContent, /价格 \$42 和 \$50/);
  assert.ok([...mathView.container.querySelectorAll('code')].some(node => node.textContent === '$code$'));
  mathView.unmount();
  for (const id of ['vditorKatexStyle', 'vditorKatexScript', 'vditorKatexChemScript']) document.getElementById(id).remove();
  Vditor.mathAssetsLoaded = false;
  const failedEditor = render(h(Editor, { ...props, value: dollarText }));
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 0)); document.querySelector('link[href*="katex"]').dispatchEvent(new Event('error')); });
  assert.ok(screen.getByText(/公式资源加载失败/));
  const failedInstance = Vditor.instances.at(-1);
  assert.equal(failedInstance.getValue(), dollarText);
  assert.doesNotMatch(failedInstance.vditor.lute.Md2VditorIRDOM('$x$'), /language-math/);
  assert.equal(failedInstance.options.preview.markdown.mathBlockPreview, false);
  assert.equal(failedInstance.input.disabled, false);
  failedEditor.unmount();
  console.log('PASS shared GFM/highlighting/HTML filtering/anchors, controlled editing, uploads/errors/limits and stale upload isolation');
} finally {
  cleanup(); globalThis.fetch = realFetch; await window.happyDOM.abort();
}
